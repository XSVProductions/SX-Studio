import 'package:sx_engine/sx_engine.dart';
import 'package:test/test.dart';

void main() {
  tearDown(() => psFlavor = PsFlavor.winPs51);

  test('the app copies Windows PowerShell 5.1 unless a test says otherwise', () {
    expect(psFlavor, PsFlavor.winPs51);
  });

  group('"\$d" of a double', () {
    // Text and expected answers from "$d", [string]$d and '{0}' -f $d under
    // Windows PowerShell 5.1 (all three agree).
    const winPs51 = {
      '110.00000000000001': '110',
      '-110.00000000000001': '-110',
      '0.30000000000000004': '0.3',
      '1.1': '1.1',
      '4.35': '4.35',
      '45': '45',
      '-1.5': '-1.5',
      '-0.0': '0',
      '1e-5': '1E-05',
      '5e-5': '5E-05',
      '1.5e-5': '1.5E-05',
      '0.0001': '0.0001',
      '0.00012345': '0.00012345',
      '0.000099999999999999991': '0.0001',
      '0.00001234567890123456': '1.23456789012346E-05',
      '1e-7': '1E-07',
      '1e14': '100000000000000',
      '999999999999999': '999999999999999',
      '123456789012345.6': '123456789012346',
      '999999999999999.9': '1E+15',
      '1e15': '1E+15',
      '1234567890123456': '1.23456789012346E+15',
      '9999999999999998': '1E+16',
      '1e20': '1E+20',
      '1.7976931348623157e308': '1.79769313486232E+308',
      '5e-324': '4.94065645841247E-324',
      '1.23456789012345': '1.23456789012345',
      '1.234567890123456': '1.23456789012346',
      '12.345678901234567': '12.3456789012346',
      '0.99999999999999989': '1',
      '0.33333333333333331': '0.333333333333333',
      '0.66666666666666663': '0.666666666666667',
      '33.333333333333336': '33.3333333333333',
      '29.000000000000004': '29',
    };

    test('Windows PowerShell 5.1: 15 significant digits', () {
      expect({for (final t in winPs51.keys) t: psDoubleText(double.parse(t))}, winPs51);
    });

    test('PowerShell 7: the shortest text that reads back the same', () {
      psFlavor = PsFlavor.ps7;
      const ps7 = {
        '110.00000000000001': '110.00000000000001',
        '0.30000000000000004': '0.30000000000000004',
        '45': '45',
        '-0.0': '-0',
        '1e-5': '1E-05',
        '0.0001': '0.0001',
        '1e14': '100000000000000',
        '1e15': '1E+15',
        '1234567890123456': '1.234567890123456E+15',
        '9999999999999998': '9.999999999999998E+15',
        '0.33333333333333331': '0.3333333333333333',
        '5e-324': '5E-324',
      };
      expect({for (final t in ps7.keys) t: psDoubleText(double.parse(t))}, ps7);
    });
  });
}
